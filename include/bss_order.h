#define BSS_ORDER_PAD(n)
#else
#define BSS_ORDER_PAD(n) BSS_PAD_LINE_(n, __LINE__)
#define BSS_PAD_LINE_(n, line) BSS_PAD_LINE__(n, line)
#define BSS_PAD_LINE__(n, line) BSS_PAD_##n(BssOrderPad_##line##_)

