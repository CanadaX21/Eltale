/*
 * IDO 5.3 lays out a compilation unit's .bss in the order of each variable's block number modulo 256
 * (rules in tools/bss_order.py). With -g, every new declaration takes a block number, headers
 * included: a header that gains or loses declarations moves the .bss of the units that include it.
 * BSS_ORDER_PAD(n) takes n more block numbers (n forward struct declarations, nothing else: no code,
 * no data), so a unit keeps the original game's .bss order when the declarations before its state
 * change. The values are computed and kept by tools/bss_order.py; nobody writes them by hand. 0 means
 * a whole turn (256 declarations): the same order, and the slot stays visible to the tool. What
 * the slots cannot absorb (a unit's .bss declared out of storage order; the stretches where a unit's
 * function statics sit among its other .bss) is in docs/DECLARATIONS.md, and the tool refuses it.
 * A build that does not need the original layout can define NO_BSS_ORDER_PADS to drop them.
 * Written by tools/make_bss_order_h.py; change that, not this file.
 */

