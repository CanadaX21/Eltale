s32 __amDma(s32 addr, s32 len, void* state) {
    void* foundBuffer;
    s32 delta;
    AMDMABuffer* dmaPtr;
    AMDMABuffer* lastDmaPtr;
    s32 addrEnd;
    s32 buffEnd;

    lastDmaPtr = NULL;
    dmaPtr = dmaState.firstUsed;
    addrEnd = addr + len;

    while (dmaPtr != NULL) {
        buffEnd = dmaPtr->startAddr + 0x500;
        if (dmaPtr->startAddr > addr) {
            break;
        } else if (addrEnd <= buffEnd) {
            dmaPtr->lastFrame = audFrameCt;
            foundBuffer = dmaPtr->ptr + addr - dmaPtr->startAddr;
            return osVirtualToPhysical(foundBuffer);
        }
        lastDmaPtr = dmaPtr;
        dmaPtr = (AMDMABuffer*)dmaPtr->node.next;
    }

    dmaPtr = dmaState.firstFree;
    dmaState.firstFree = (AMDMABuffer*)dmaPtr->node.next;
    alUnlink((ALLink*)dmaPtr);

    if (lastDmaPtr != NULL) {
        alLink((ALLink*)dmaPtr, (ALLink*)lastDmaPtr);
    } else if (dmaState.firstUsed != NULL) {
        lastDmaPtr = dmaState.firstUsed;
        dmaState.firstUsed = dmaPtr;
        dmaPtr->node.next = (ALLink*)lastDmaPtr;
        dmaPtr->node.prev = NULL;
        lastDmaPtr->node.prev = (ALLink*)dmaPtr;
    } else {
        dmaState.firstUsed = dmaPtr;
        dmaPtr->node.next = NULL;
        dmaPtr->node.prev = NULL;
    }

    foundBuffer = dmaPtr->ptr;
    delta = addr & 1;
    addr -= delta;
    dmaPtr->startAddr = addr;
    dmaPtr->lastFrame = audFrameCt;
    osPiStartDma(&audDMAIOMesgBuf[nextDMA++], OS_MESG_PRI_NORMAL, OS_READ, addr, foundBuffer, 0x500, &audDMAMessageQ);

    return osVirtualToPhysical(foundBuffer) + delta;
}
extern AMDMABuffer dmaBuffs[32];  /* dmaBuffs */
ALDMAproc __amDmaNew(AMDMAState** state) {
    s32 i;

    if (!dmaState.initialized) {
        dmaState.firstFree = &dmaBuffs[0];
        dmaState.firstUsed = NULL;
        for (i = 0; i < 32 - 1; i++) {
            alLink((ALLink*)&dmaBuffs[i + 1], (ALLink*)&dmaBuffs[i]);
            dmaBuffs[i].ptr = alHeapDBAlloc(0, 0, &gAudioHeap, 1, 0x500);
        }
        dmaState.initialized = 1;
    }
    *state = &dmaState;
    return __amDma;
}
void __clearAudioDMA(void) {
    AMDMABuffer* dmaPtr;
    AMDMABuffer* nextPtr;

    dmaPtr = dmaState.firstUsed;
    while (dmaPtr != NULL) {
        nextPtr = (AMDMABuffer*)dmaPtr->node.next;
        if (dmaPtr->lastFrame + 2 < audFrameCt) {
            if (dmaState.firstUsed == dmaPtr) {
                dmaState.firstUsed = (AMDMABuffer*)dmaPtr->node.next;
            }
            alUnlink((ALLink*)dmaPtr);
            if (dmaState.firstFree != NULL) {
                alLink((ALLink*)dmaPtr, (ALLink*)dmaState.firstFree);
            } else {
                dmaState.firstFree = dmaPtr;
                dmaPtr->node.next = NULL;
                dmaPtr->node.prev = NULL;
            }
        }
        dmaPtr = nextPtr;
    }
    nextDMA = 0;
    audFrameCt++;
}
#define NUM_FIELDS 1               /* video fields per audio frame, as in the SDK's audiomgr.h */
extern s32 gAcmdLen;             /* alAudioFrame's command count */
/* The audio thread: the SDK audio manager's frame loop on the nnsched scheduler. On each retrace it builds one audio
   frame into one of two command lists, runs it as an RSP task and hands the output buffer (one of three) to the AI.
   After PRE-NMI it fades both music players out over 28 frames, then stops making frames. */
void AudioThread(NNSched* sc) {
    static s32 sCurAcmdList = 0;               /* the task and command list being built, 0 or 1 */
    static s32 sFrameCount = 1;                /* audio frames made; the output buffer is this % 3 */
    static s16 sFrameSamples[3] = { 0, 0, 0 }; /* each output buffer's sample count */
    OSMesgQueue frameMQ;
    OSMesg frameMsgBuf[8];
    OSMesgQueue doneMQ;
    OSMesg doneMsgBuf[8];
    NNScClient client;
    f32 fsize;
    s32 minFrameSize;
    s32 buf;
    s32 frameSize;
    u32 i;
    u32 samplesLeft;
    NNScTask* task;
    OSMesgQueue* audioMQ;
    NNScTask tasks[2];
    Acmd* cmdp;
    NNScMsg* msg;
    u32 state;                                 /* 0 playing, 1 fading out after PRE-NMI, 2 silent */
    s16 startVol[2];
    s16 vol[2];
    Acmd* cmdList;
    u32 outPhys;

    samplesLeft = 0;
    msg = NULL;
    state = 0;
    fsize = (f32)NUM_FIELDS * gSynConfig.outputRate / (f32)60;
    frameSize = (s32)fsize;
    if (frameSize < fsize) {
        frameSize++;
    }
    if (frameSize & 0xF) {
        frameSize = (frameSize & ~0xF) + 0x10;
    }
    osCreateMesgQueue(&frameMQ, frameMsgBuf, 8);
    osCreateMesgQueue(&doneMQ, doneMsgBuf, 8);
    nnScAddClient(sc, &client, &frameMQ);
    audioMQ = nnScGetAudioMQ(sc);
    while (1) {
        osRecvMesg(&frameMQ, (OSMesg*)&msg, OS_MESG_BLOCK);
        switch (*msg) {
            case NN_SC_RETRACE_MSG:
                UpdateSoundPlayer();
                switch (state) {
                    case 1:
                        for (i = 0; i < 2; i++) {
                            vol[i] -= startVol[i] / 28;
                            if (vol[i] < 0) {
                                vol[i] = 0;
                            }
                            alCSPSetVol(&gMusicSlots[i].player, vol[i]);
                        }
                        if (vol[0] == 0 && vol[1] == 0) {
                            state++;
                        }
                        /* fall through: the frame is still made */
                    default:
                        minFrameSize = frameSize - 16;
                        task = &tasks[sCurAcmdList];
                        cmdList = gAcmdLists[sCurAcmdList];
                        buf = sFrameCount % 3;
                        __clearAudioDMA();
                        outPhys = osVirtualToPhysical(gAudioBuffers[buf]);
                        /* 0x60: 16 + the SDK's EXTRA_SAMPLES (80) */
                        sFrameSamples[buf] = (frameSize - samplesLeft + 0x60) & 0xFFF0;
                        if (sFrameSamples[buf] < minFrameSize) {
                            sFrameSamples[buf] = minFrameSize;
                        }
                        cmdp = alAudioFrame(cmdList, &gAcmdLen, (s16*)outPhys, sFrameSamples[buf]);
                        task->next = NULL;
                        task->msgQ = &doneMQ;
                        task->msg = NULL;
                        task->list.t.data_ptr = (u64*)gAcmdLists[sCurAcmdList];
                        task->list.t.data_size = (cmdp - gAcmdLists[sCurAcmdList]) * sizeof(Acmd);
                        task->list.t.type = M_AUDTASK;
                        task->list.t.flags = 0;
                        task->list.t.ucode_boot = (u64*)rspbootTextStart;
                        task->list.t.ucode_boot_size = (s32)rspbootTextEnd - (s32)rspbootTextStart;
                        task->list.t.ucode = (u64*)aspMainTextStart;
                        task->list.t.ucode_data = (u64*)aspMainDataStart;
                        task->list.t.ucode_data_size = SP_UCODE_DATA_SIZE;
                        task->list.t.dram_stack = NULL;
                        task->list.t.dram_stack_size = 0;
                        task->list.t.output_buff = NULL;
                        task->list.t.output_buff_size = 0;
                        task->list.t.yield_data_ptr = NULL;
                        task->list.t.yield_data_size = 0;
                        osSendMesg(audioMQ, (OSMesg)task, OS_MESG_BLOCK);
                        samplesLeft = osAiGetLength() >> 2;
                        sCurAcmdList ^= 1;
                        sFrameCount++;
                        osRecvMesg(&doneMQ, NULL, OS_MESG_BLOCK);
                        osAiSetNextBuffer(gAudioBuffers[buf], sFrameSamples[buf] * 4);
                        break;
                    case 2:
                        break;
                }
                break;
            case NN_SC_PRE_NMI_MSG:
                state++;
                startVol[0] = alCSPGetVol(&gMusicSlots[0].player);
                startVol[1] = alCSPGetVol(&gMusicSlots[1].player);
                vol[1] = startVol[1];
                vol[0] = startVol[0];
        }
    }
}

