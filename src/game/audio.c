extern u32* gSoundScriptLoop;
extern s32 gLoopingSoundSlot;              /* the slot being updated (StepLoopingSound reads it) */
extern u32* gSlotScriptPos0;
extern u32* gSlotScriptPos1;
extern u32* gSlotScriptPos2;
extern u32* gSlotScriptPos3;
extern u32* gSlotScriptPos4;
extern u32* gSlotScriptLoop0;
extern u32* gSlotScriptLoop1;
extern u32* gSlotScriptLoop2;
extern u32* gSlotScriptLoop3;
extern u32* gSlotScriptLoop4;
void UpdateSoundPlayer(void) {
    for (gLoopingSoundSlot = 0; gLoopingSoundSlot < 5; gLoopingSoundSlot++) {
        if (gLoopingSoundFrames[gLoopingSoundSlot] != 0) {
            switch (gLoopingSoundSlot) {
                case 0:
                    gSoundScriptPos = gSlotScriptPos0;
                    gSoundScriptLoop = gSlotScriptLoop0;
                    break;
                case 1:
                    gSoundScriptPos = gSlotScriptPos1;
                    gSoundScriptLoop = gSlotScriptLoop1;
                    break;
                case 2:
                    gSoundScriptPos = gSlotScriptPos2;
                    gSoundScriptLoop = gSlotScriptLoop2;
                    break;
                case 3:
                    gSoundScriptPos = gSlotScriptPos3;
                    gSoundScriptLoop = gSlotScriptLoop3;
                    break;
                case 4:
                    gSoundScriptPos = gSlotScriptPos4;
                    gSoundScriptLoop = gSlotScriptLoop4;
                    break;
            }
            if (--gLoopingSoundFrames[gLoopingSoundSlot] == 0) {
                StepLoopingSound();
            }
        }
    }
    if (gMusicRequest != 0xFF) {
        SwitchMusic(gMusicRequest);
    }
    if (gMusicFadeOutStep != 0) {
        StepMusicFadeOut();
    }
    if (gMusicFadeInStep != 0) {
        StepMusicFadeIn();
    }
    ProcessSoundQueue();
}
void SelectSoundScript(s32 index) {
    if ((index >= 0) && (index < 0x47)) {
        gSoundScriptPos = gSoundScripts[index];
        return;
    }
    gSoundScriptPos = gSoundScripts[0];
}
s32 ChangeMusicIfIdle(void) {
    if ((gMusicFadeOutStep != 0) || (gMusicFadeInStep != 0)) {
        return 1;
    }
    SwitchMusic();
    return 0;
}
void SwitchMusic(s32 bgm) {
    u32 seq;

    gMusicRequest = bgm;
    if (bgm == 1) {
        if (gLoadedSequence == 0xFF) {
            if (LoadMusicSequences(0) != 0) {
                return;
            }
        } else if (gMusicSlots[0].player.state != AL_STOPPED) {
            alCSPStop(&gMusicSlots[0].player);
            return;
        }
        gActiveMusicSlot = 1;
        alCSPSetVol(&gMusicSlots[1].player, 0x7FFF);
        gMusicSlotVolumes[1] = 0x7FFF;
        StartSequence(1);
        gMusicRequest = 0xFF;
        return;
    }
    gActiveMusicSlot = 0;
    alCSPStop(&gMusicSlots[1].player);
    if (bgm >= 0x50) {
        seq = bgm - 0x50;
        if (seq == gLoadedSequence || LoadMusicSequences(seq) == 0) {
            StartSequence(0);
            alCSPSetVol(&gMusicSlots[0].player, 0);
            gMusicSlotVolumes[0] = 0;
            gMusicFadeInStep = 0x100;
            gLoadedSequence = seq;
            gMusicRequest = 0xFF;
        }
    } else if (bgm == gLoadedSequence || LoadMusicSequences(bgm) == 0) {
        StartSequence(0);
        alCSPSetVol(&gMusicSlots[0].player, 0x7FFF);
        gMusicSlotVolumes[0] = 0x7FFF;
        gLoadedSequence = bgm;
        gMusicRequest = 0xFF;
    }
}
void QueueSound(s32 sound) {
    static s32 i;

    i = gSoundQueueWrite;
    gSoundQueue[i] = sound;
    gSoundQueueVolumeScale[i] = 0;
    gSoundQueuePan[i] = 0x40;
    i++;
    gSoundQueueWrite = i & 7;
}

void PushSoundQueue(s32 sound, s32 volumeScale, s32 pan) {
    static s32 i;

    i = gSoundQueueWrite;
    gSoundQueue[i] = sound;
    gSoundQueueVolumeScale[i] = volumeScale;
    gSoundQueuePan[i] = pan;
    i++;
    gSoundQueueWrite = i & 7;
}

extern s32 gSoundQueueWrite;
void ProcessSoundQueue(void) {
    s32 idx = gSoundQueueRead;
    u32 sound;
    s32 i;
    s32 prev;

    if (gSoundQueue[idx] != 0xFF) {
        sound = gSoundQueue[idx];
        gSoundQueue[idx] = 0xFF;
        gSoundQueueRead = (idx + 1) & 7;
        gLoopingSoundSlot = gSoundQueueRead & 3;
        SelectSoundScript(sound);
        if (*gSoundScriptPos != 0) {
            gLoopingSoundSlot = 4;
            gSlotVolumeScale[gLoopingSoundSlot] = gSoundQueueVolumeScale[idx];
            gSlotPan[gLoopingSoundSlot] = gSoundQueuePan[idx];
            prev = gLoopingSounds[4];
            if (sound != gLoopingSounds[4] && gLoopingSounds[4] != 0xFF) {
                StopSound(gLoopingSounds[4]);
                gLoopingSounds[4] = sound;
                StartSound(sound);
            }
            if (gLoopingSounds[4] == 0xFF) {
                gLoopingSounds[4] = sound;
                StartSound(sound);
            }
        } else {
            gSlotVolumeScale[gLoopingSoundSlot] = gSoundQueueVolumeScale[idx];
            gSlotPan[gLoopingSoundSlot] = gSoundQueuePan[idx];
            prev = -1;
            if (gLoopingSoundFrames[gLoopingSoundSlot] != 0 && gLoopingSounds[gLoopingSoundSlot] != sound) {
                StopSound(gLoopingSounds[gLoopingSoundSlot]);
            }
            for (i = 0; i < 4; i++) {
                if (gLoopingSounds[i] == sound) {
                    gLoopingSoundFrames[i] = 0;
                    gLoopingSounds[i] = 0xFF;
                }
            }
            gLoopingSounds[gLoopingSoundSlot] = sound;
            StartSound(sound);
        }
        if (prev != sound) {
            gSoundScriptPos++;
            StepLoopingSound();
        }
    } else {
        gSoundQueueRead = gSoundQueueWrite;
    }
}

extern u32 gSlotLastVolume[5];            /* last volume per slot */
void StepLoopingSound(void) {
    s32 snd;
    u32 vol;
    u32 word;

    snd = gLoopingSounds[gLoopingSoundSlot];
    if (*gSoundScriptPos == 0xFFFF) {
        StopSound(snd);
        return;
    }
    if (*gSoundScriptPos == 0xFFFD) {
        gSoundScriptLoop = gSoundScriptPos;
        gSoundScriptPos++;
    }
    if (*gSoundScriptPos == 0xFFFE) {
        gSoundScriptPos = gSoundScriptLoop;
        gSoundScriptPos++;
    }
    gLoopingSoundFrames[gLoopingSoundSlot] = *gSoundScriptPos;
    gSoundScriptPos++;
    if (*gSoundScriptPos != 0xFFFF) {
        alSndpSetSound(&gSndPlayer, gSoundIds[snd]);
        alSndpSetPitch(&gSndPlayer, gSoundPitchTable[*gSoundScriptPos]);
    }
    gSoundScriptPos++;
    if (*gSoundScriptPos != 0xFFFF) {
        vol = *gSoundScriptPos;
        gSlotLastVolume[gLoopingSoundSlot] = vol;
        if (gSlotVolumeScale[gLoopingSoundSlot] != 0) {
            vol = gSlotVolumeScale[gLoopingSoundSlot] * (vol >> 8);
        }
        alSndpSetSound(&gSndPlayer, gSoundIds[snd]);
        alSndpSetVol(&gSndPlayer, vol);
    } else if (gSlotVolumeScale[gLoopingSoundSlot] != 0) {
        word = gSlotLastVolume[gLoopingSoundSlot];
        vol = gSlotVolumeScale[gLoopingSoundSlot] * (word >> 8);
        alSndpSetSound(&gSndPlayer, gSoundIds[snd]);
        alSndpSetVol(&gSndPlayer, vol);
    }
    gSoundScriptPos++;
    if (*gSoundScriptPos != 0xFFFF && gSlotPan[gLoopingSoundSlot] == 0x40) {
        alSndpSetSound(&gSndPlayer, gSoundIds[snd]);
        alSndpSetPan(&gSndPlayer, *gSoundScriptPos);
    }
    if (gSlotPan[gLoopingSoundSlot] != 0x40) {
        alSndpSetSound(&gSndPlayer, gSoundIds[snd]);
        alSndpSetPan(&gSndPlayer, gSlotPan[gLoopingSoundSlot]);
    }
    gSoundScriptPos++;
    switch (gLoopingSoundSlot) {
        case 0:
            gSlotScriptPos0 = gSoundScriptPos;
            gSlotScriptLoop0 = gSoundScriptLoop;
            break;
        case 1:
            gSlotScriptPos1 = gSoundScriptPos;
            gSlotScriptLoop1 = gSoundScriptLoop;
            break;
        case 2:
            gSlotScriptPos2 = gSoundScriptPos;
            gSlotScriptLoop2 = gSoundScriptLoop;
            break;
        case 3:
            gSlotScriptPos3 = gSoundScriptPos;
            gSlotScriptLoop3 = gSoundScriptLoop;
            break;
        case 4:
            gSlotScriptPos4 = gSoundScriptPos;
            gSlotScriptLoop4 = gSoundScriptLoop;
            break;
    }
}

void StepMusicFadeOut(void) {
    s32 slot = gActiveMusicSlot;
    s32* volume = &gMusicSlotVolumes[slot];
    s32 v;

    v = *volume -= gMusicFadeOutStep;
    if (v < 0 || v > gMusicVolume.volume) {
        *volume = gMusicVolume.volume;
        alCSPStop(MUSIC_PLAYER(slot));
        gMusicFadeOutStep = 0;
        return;
    }
    alCSPSetVol(MUSIC_PLAYER(slot), v);
}
void StepMusicFadeIn(void) {
    s32 slot = gActiveMusicSlot;
    s32* volume = &gMusicSlotVolumes[slot];
    s32 v;

    v = *volume += gMusicFadeInStep;
    if (v < 0 || v > gMusicVolume.volume) {
        *volume = gMusicVolume.volume;
        gMusicFadeInStep = 0;
        return;
    }
    alCSPSetVol(MUSIC_PLAYER(slot), v);
}
/* If the current slot's player has stopped, load sequence arg0 into slot 0 and sequence 1 into slot 1 and return 0;
   otherwise stop both players and return 1. */
s32 LoadMusicSequences(s32 seq) {
    if (MUSIC_PLAYER(gActiveMusicSlot)->state == AL_STOPPED) {
        LoadSequence(0, seq);
        LoadSequence(1, 1);
        return 0;
    }
    alCSPStop(&gMusicSlots[0].player);
    alCSPStop(&gMusicSlots[1].player);
    return 1;
}
s32 StartMusicFadeOut(u32 frames) {
    if ((gMusicFadeOutStep != 0) || (gMusicFadeInStep != 0)) {
        return 1;
    }
    gMusicFadeOutStep = 0x8000U / frames;
    return 0;
}
void StopLoopingSounds(void) {
    s32 i;
    u32 sound;

    for (i = 0; i < 5; i++) {
        sound = gLoopingSounds[i];
        if (sound != 0xFF) {
            StopSound(sound);
        }
        gLoopingSoundFrames[i] = 0;
        gLoopingSounds[i] = 0xFF;
    }
}
void StopLoopingSoundSlot4(void) {
    if (gLoopingSounds[4] != 0xFF) {
        StopSound(gLoopingSounds[4]);
    }
    gLoopingSoundFrames[4] = 0;
    gLoopingSounds[4] = 0xFF;
}
u8 ApplyMusicVolume(u32 BGMVolume)
{
  if ((gMusicFadeOutStep != 0) || (gMusicFadeInStep != 0))
  {
    return 1;
  }
  gMusicVolume.volume = (BGMVolume << 7) + 0x7F;
  alCSPSetVol(&gMusicSlots[0].player, gMusicVolume.volume);
  alCSPSetVol(&gMusicSlots[1].player, gMusicVolume.volume);
  gMusicSlotVolumes[0] = gMusicVolume.volume;
  gMusicSlotVolumes[1] = gMusicVolume.volume;
  return 0;
}
