void LoadSequence(s32 slot, s32 seq) {
    u8* rom = gSeqFile->seqArray[seq].offset;
    s32 len = gSeqFile->seqArray[seq].len;

    if (len & 1) {
        len++;
    }
    ReadAudioRom((u32)rom, gMusicSlots[slot].seqBuffer, len);
    gMusicSlots[slot].seqId = seq;
}
s32 StartSequence(s32 slot) {
    MusicSlot* music = &gMusicSlots[slot];
    ALCSeq* seq = &music->seq;
    ALCSPlayer* player;
    s32 chan;

    if (music->player.state != AL_STOPPED) {
        return 0;
    }
    alCSeqNew(seq, music->seqBuffer);
    player = &music->player;
    alCSPSetSeq(player, seq);
    alCSPPlay(player);
    for (chan = 0; chan < 16; chan++) {
        alCSPSetChlFXMix(player, chan, 0x18);
    }
    return 1;
}
