"""objdiff support (github.com/encounter/objdiff): a per-function comparison of the C objects with
those of the last build whose ROM matched. Standard library only. Run from the
project root after ./configure (configure.py calls it at the end):

    python3 tools/objdiff_gen.py

For every C file the build compiles (build/src/X.c.o from src/X.c), it adds:
  - target: expected/build/src/X.c.o, the matching build's object (the build's last
    step, tools/make_expected.py, copies build/ to expected/ whenever the ROM matches);
  - base:   build/objdiff/src/X.c.o, the same file compiled with its
    `#pragma GLOBAL_ASM(...)` lines removed, so functions still in assembly show up as
    not decompiled yet, and a function counts once its C matches the original.
It writes objdiff.ninja (included from build.ninja) and objdiff.json.
"""
import json, os, re

BUILD = re.compile(r'^build (build/(src/\S+\.c)\.o): (\S+) (src/\S+\.c)\s*$')

with open('build.ninja', encoding='utf-8') as f:
    lines = f.read().splitlines()

units, out = [], [
    '# generated by tools/objdiff_gen.py: objects without GLOBAL_ASM functions, for objdiff',
    'rule strip_global_asm',
    "  command = sed -E '/^[[:space:]]*#[[:space:]]*pragma[[:space:]]+GLOBAL_ASM/d' $in > $out",
    '  description = objdiff source $in',
    '# objdiff target: the matching object with the file-end alignment padding left out of the',
    '# last function (tools/trim_padding.py); compiled C gets that padding from the linker',
    'rule trim_padding',
    '  command = python3 tools/trim_padding.py $in $out',
    '  description = objdiff target $in',
]
for line in lines:
    m = BUILD.match(line)
    if not m:
        continue
    obj, rel, rule, src = m.groups()
    stripped = f'build/objdiff/{rel}'
    out.append(f'build {stripped}: strip_global_asm {src}')
    out.append(f'build build/objdiff/{rel}.o: {rule} {stripped}')
    # quoted #includes are found next to the original file
    out.append(f'  CFLAGS = $CFLAGS -I {os.path.dirname(src)}')
    out.append(f'build build/objdiff_target/{rel}.o: trim_padding expected/{obj}')
    units.append({'name': rel[:-2], 'target_path': f'build/objdiff_target/{rel}.o', 'base_path': f'build/objdiff/{rel}.o',
                  'metadata': {'source_path': src}})

with open('objdiff.ninja', 'w', encoding='utf-8') as f:
    f.write('\n'.join(out) + '\n')
if 'subninja objdiff.ninja' not in lines:
    with open('build.ninja', 'a', encoding='utf-8') as f:
        f.write('\nsubninja objdiff.ninja\n')

cfg = {
    '$schema': 'https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json',
    'custom_make': 'ninja',
    'custom_args': [],
    'build_target': False,
    'build_base': True,
    'watch_patterns': ['*.c', '*.h', '*.s'],
    'units': units,
}
with open('objdiff.json', 'w', encoding='utf-8') as f:
    json.dump(cfg, f, indent=2)
print(f'objdiff: {len(units)} units')
