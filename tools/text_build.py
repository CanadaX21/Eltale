"""text_build.py IN.dialogue.txt OUT.s OUT.h | IN.npcnames.txt OUT.s: encode
one part of the dialogue bank, or one NPC file's name pool, at build time.

Reads the part's source text (assets/<dir>/<part>.dialogue.txt, which tools/splat_ext/dialogue.py writes from the
ROM) and the definition (text/encoding.json, through tools/text_codec.py), and writes:
  - OUT.s: the part's bytes in .data, the strings in file order, each on the bank's alignment with 0xFF fill, the part
    padded with 0xFF; a global label at the part's start (the definition's "label": the sign base is defined from it);
  - OUT.h: each string's name defined as its offset from the part's start (what the NPC and sign records hold), and
    the part's size. The header is rewritten only when it changes, so the files that include it recompile only then.
It stops on what the game's code could not read: a string longer than the code reads (the part's limit; 0x20 for a
string marked `name`), an offset past 0xFFFF (the records hold u16), an empty string (it would read as fill), and a
part whose first string is not the one the definition fixes there (`first`, where a part has one).
A name pool (assets/<file>/names.npcnames.txt, tools/splat_ext/npcnames.py; the definition's `npc_names` bank):
OUT.s defines each string's NAME, a global label, at its bytes: the strings in file order, each on the pool's 4-byte
step with zero fill, the pool padded to 16 with zeros (the original's layout). It stops on a name longer than the
code reads (0x20: StartNPCText copies that many into gSpeakerName), an empty one, or a NAME that is no C identifier.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import text_codec                                       # noqa: E402


def c_define(root, name):
    """the value of `#define NAME value` in the project's headers (include/), or None"""
    pat = re.compile(r'^[ \t]*#[ \t]*define[ \t]+%s[ \t]+(0x[0-9A-Fa-f]+|[0-9]+)\b' % re.escape(name), re.M)
    for dp, dn, fn in os.walk(os.path.join(root, 'include')):
        for f in sorted(fn):
            if f.endswith('.h'):
                m = pat.search(open(os.path.join(dp, f), encoding='utf-8', errors='replace').read())
                if m:
                    return int(m.group(1), 0)
    return None


def main(src, out_s, out_h):
    root = os.path.dirname(HERE)
    enc = text_codec.Encoding(os.path.join(root, 'text', 'encoding.json'))
    bank = enc.data['banks']['dialogue']
    stem = os.path.basename(src)[:-len('.dialogue.txt')]
    part = next((p for p in bank['parts'] if p['name'] == stem), None)
    if part is None:
        sys.exit('text_build: %s: no part %r in text/encoding.json' % (src, stem))
    limit, name_limit = int(part['limit'], 0), int(part.get('name limit', part['limit']), 0)
    if part.get('limit symbol'):                      # the C constant the code sizes the text with
        want = c_define(root, part['limit symbol'])
        if want != limit:
            sys.exit('text_build: text/encoding.json gives part %s the limit 0x%X; the C code\'s %s is %s: '
                     'change both together' % (stem, limit, part['limit symbol'],
                                              'not defined in include/' if want is None else '0x%X' % want))
    names, strings = [], []
    try:
        entries = text_codec.read_source(src)
    except text_codec.TextError as ex:
        sys.exit('text_build: %s' % ex)
    for name, marks, body in entries:
        try:
            b = enc.encode(body)
        except text_codec.TextError as ex:
            sys.exit('text_build: %s: @%s: %s' % (src, name, ex))
        if len(b) < 2:
            sys.exit('text_build: %s: @%s is empty (a lone 0xFF would read as fill)' % (src, name))
        cap = name_limit if 'name' in marks else limit
        if len(b) > cap:
            sys.exit('text_build: %s: @%s is 0x%X bytes; the code reads at most 0x%X' % (src, name, len(b), cap))
        names.append(name)
        strings.append(b)
    if part.get('first') and (not names or names[0] != part['first']):
        sys.exit('text_build: %s: the first string must stay @%s: %s' % (src, part['first'], part.get('first why', '')))
    data, offsets = enc.layout(strings, bank['align'], bank['part pad'])
    for name, off in zip(names, offsets):
        if off > 0xFFFF:
            sys.exit('text_build: %s: @%s starts at 0x%X, past what a u16 offset holds' % (src, name, off))
    label = part['label']
    s = ['# generated by tools/text_build.py from %s: do not edit' % src,
         '.section .data', '.globl %s' % label, '%s:' % label]
    for k in range(0, len(data), 16):
        s.append('.byte ' + ', '.join('0x%02X' % x for x in data[k:k + 16]))
    with open(out_s, 'w', newline='\n') as f:
        f.write('\n'.join(s) + '\n')
    guard = 'DIALOGUE_%s_H' % stem.upper()
    h = ['/* generated by tools/text_build.py from %s: do not edit. Each string\'s offset from the part\'s start. */' % src,
         '#ifndef %s' % guard, '#define %s' % guard]
    h += ['#define %s 0x%04X' % (n, o) for n, o in zip(names, offsets)]
    h += ['#define %s_SIZE 0x%X' % (part['prefix'], len(data)), '#endif', '']
    text = '\n'.join(h)
    old = open(out_h).read() if os.path.isfile(out_h) else None
    if old != text:
        os.makedirs(os.path.dirname(out_h) or '.', exist_ok=True)
        with open(out_h, 'w', newline='\n') as f:
            f.write(text)


def names(src, out_s):
    root = os.path.dirname(HERE)
    enc = text_codec.Encoding(os.path.join(root, 'text', 'encoding.json'))
    bank = enc.data['banks']['npc_names']
    step, pad, limit = int(bank['align']), int(bank['pool pad']), int(bank['limit'], 0)
    try:
        entries = text_codec.read_source(src)
    except text_codec.TextError as ex:
        sys.exit('text_build: %s' % ex)
    s = ['# generated by tools/text_build.py from %s: do not edit' % src, '.section .data']
    pos = 0
    for name, marks, body in entries:
        if not re.match(r'^[A-Za-z_]\w*$', name):
            sys.exit('text_build: %s: @%s is no C identifier' % (src, name))
        try:
            b = enc.encode(body)
        except text_codec.TextError as ex:
            sys.exit('text_build: %s: @%s: %s' % (src, name, ex))
        if len(b) < 2:
            sys.exit('text_build: %s: @%s is empty' % (src, name))
        if len(b) > limit:
            sys.exit('text_build: %s: @%s is 0x%X bytes; the code reads at most 0x%X' % (src, name, len(b), limit))
        if pos % step:
            s.append('.byte ' + ', '.join(['0x00'] * (step - pos % step)))
            pos += step - pos % step
        s += ['.globl %s' % name, '%s:' % name]
        for k in range(0, len(b), 16):
            s.append('.byte ' + ', '.join('0x%02X' % x for x in b[k:k + 16]))
        pos += len(b)
    if pos % pad:
        s.append('.byte ' + ', '.join(['0x00'] * (pad - pos % pad)))
    with open(out_s, 'w', newline='\n') as f:
        f.write('\n'.join(s) + '\n')


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1].endswith('.npcnames.txt'):
        names(*sys.argv[1:])
    elif len(sys.argv) != 4:
        sys.exit(__doc__)
    else:
        main(*sys.argv[1:])
